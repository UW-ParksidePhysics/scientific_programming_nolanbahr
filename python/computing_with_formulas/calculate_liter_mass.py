# volume of one liter in cubic centimeters
liter_volume = 1000

# densities
iron_density = 7.87
gasoline_density = 0.755
ice_density = 0.92
human_body_density = 1.0
silver_density = 10.49
platinum_density = 21.45


# compute masses using m = density * volume
iron_mass = iron_density * liter_volume
gasoline_mass = gasoline_density * liter_volume
ice_mass = ice_density * liter_volume
human_body_mass = human_body_density * liter_volume
silver_mass = silver_density * liter_volume
platinum_mass = platinum_density * liter_volume


print("Mass of one liter of iron:", iron_mass)
print("Mass of one liter of gasoline:", gasoline_mass)
print("Mass of one liter of ice:", ice_mass)
print("Mass of one liter of human body:", human_body_mass)
print("Mass of one liter of silver:", silver_mass)
print("Mass of one liter of platinum:", platinum_mass)
